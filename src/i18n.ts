const originalText = new WeakMap<Node, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
let originalDocumentTitle: string | undefined;

function translateValue(value: string): string {
  const separator = " · ";
  if (value.includes(separator)) {
    return value.split(separator).map(translateValue).join(separator);
  }
  if (value.includes("Tous droits réservés.")) {
    return value.replace("Tous droits réservés.", "All rights reserved.");
  }
  const trimmed = value.trim();
  const normalized = trimmed.replace(/\s+/g, " ");
  const translated = translations[normalized];
  if (!translated) return value;
  const start = value.indexOf(trimmed);
  return `${value.slice(0, start)}${translated}${value.slice(start + trimmed.length)}`;
}

function translateDocument(locale: Locale) {
  document.documentElement.lang = locale;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue ?? "");
    const source = originalText.get(node) ?? "";
    node.nodeValue = locale === "fr" ? source : translateValue(source);
    node = walker.nextNode();
  }

  const translatableAttributes = ["aria-label", "alt", "placeholder", "title", "content", "data-title", "data-description", "data-cta"];
  document.querySelectorAll("*").forEach((element) => {
    let attributes = originalAttributes.get(element);
    if (!attributes) {
      attributes = new Map<string, string>();
      originalAttributes.set(element, attributes);
    }
    translatableAttributes.forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value !== null && !attributes?.has(attribute)) attributes?.set(attribute, value);
      const source = attributes?.get(attribute);
      if (source !== undefined) element.setAttribute(attribute, locale === "fr" ? source : translateValue(source));
    });
  });
  originalDocumentTitle ??= document.title;
  document.title = locale === "fr" ? originalDocumentTitle : translateValue(originalDocumentTitle);

  document.querySelectorAll<HTMLSelectElement>("[data-language-select]").forEach((select) => {
    select.value = locale;
    const wrapper = select.closest<HTMLElement>("[data-language-picker]");
    wrapper?.querySelector("[data-language-label]")?.replaceChildren(locale === "fr" ? "Français" : "English");
    const flag = wrapper?.querySelector<HTMLElement>("[data-language-flag]");
    if (flag) {
      flag.classList.toggle("language-flag-fr", locale === "fr");
      flag.classList.toggle("language-flag-us", locale === "en");
      flag.setAttribute("aria-label", locale === "fr" ? "Drapeau français" : "Drapeau américain");
    }
  });
}

export function initializeLanguage() {
  const storedLocale = localStorage.getItem("monetalab-language");
  let locale: Locale = storedLocale === "en" ? "en" : "fr";
  translateDocument(locale);

  document.querySelectorAll<HTMLSelectElement>("[data-language-select]").forEach((select) => {
    select.addEventListener("change", () => {
      locale = select.value === "en" ? "en" : "fr";
      localStorage.setItem("monetalab-language", locale);
      translateDocument(locale);
      window.dispatchEvent(new CustomEvent("monetalab:languagechange", { detail: { locale } }));
    });
  });
}
